def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    validate_results_config_args(args)
    config_dir = resolve_config_dir_from_args(args)
    summary_dir = args.summary_dir or config_dir
    checkpoint_path = args.checkpoint_input or summary_dir / "l2_by_checkpoint.csv"
    output_dir = args.output_dir or config_figures_dir(config_dir)

    checkpoint_rows = load_checkpoint_rows(
        checkpoint_path,
        error_column=args.error_column,
        trajectory_error_column=args.trajectory_error_column,
    )
    checkpoint_rows = filter_paper_methods(checkpoint_rows)
    selected_datasets = parse_name_list(args.datasets)
    checkpoint_rows = filter_datasets(checkpoint_rows, selected_datasets)
    saved = plot_l2_trajectories(
        checkpoint_rows,
        output_dir=output_dir,
        mplconfig_dir=config_dir / "mplconfig",
        error_column=args.trajectory_error_column,
        xscale=args.xscale,
        yscale=args.yscale,
        filetype=args.filetype,
    )

    task_metrics = compute_task_metrics(checkpoint_rows, error_column=args.error_column)
    if args.normalize == "panel_best":
        task_metrics = add_panel_best_normalization(task_metrics)
    summary = summarize_for_lines(
        task_metrics,
        normalize=args.normalize,
        band=args.band,
        source_error_col=args.error_column,
    )

    suffix = ERROR_COLUMN_SUFFIXES.get(args.error_column, args.error_column)
    if args.normalize == "panel_best":
        suffix = f"{suffix}_panel_best"
    suffix = f"{suffix}{dataset_artifact_suffix(selected_datasets)}"
    stats_path = summary_dir / f"custom_line_summary_{suffix}.csv"
    stats_path.parent.mkdir(parents=True, exist_ok=True)
    summary.to_csv(stats_path, index=False)

    for metric in ("aucc",):
        path = output_dir / f"custom_{metric}_semivalue_lines_{suffix}.{args.filetype}"
        plot_metric_lines(
            summary,
            metric=metric,
            output_path=path,
            mplconfig_dir=config_dir / "mplconfig",
            normalize=args.normalize,
            band=args.band,
            yscale=args.yscale,
            method_offset=float(args.method_offset),
            source_error_col=args.error_column,
        )
        saved.append(path)

    print(f"config_dir={config_dir}")
    print(f"checkpoint_input={checkpoint_path}")
    print(f"summary_dir={summary_dir}")
    print(f"output_dir={output_dir}")
    print(f"loaded_checkpoint_rows={len(checkpoint_rows)}")
    print(f"task_metric_rows={len(task_metrics)}")
    print(f"summary_rows={len(summary)}")
    print(stats_path)
    for path in saved:
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
