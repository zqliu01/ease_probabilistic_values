def keep_method_for_paper(method: str) -> bool:
    base_method = method_base_name(method)
    if method in EXCLUDED_EXACT_METHODS:
        return False
    if base_method in EXCLUDED_BASE_METHODS:
        return False
    if base_method == "EaseSHAP_interaction_nonlinear":
        return method == EASE_FO_PAPER_METHOD
    return True


def filter_paper_methods(df: pd.DataFrame) -> pd.DataFrame:
    return df[df["method"].astype(str).map(keep_method_for_paper)].copy()


def parse_name_list(value: str | None) -> list[str] | None:
    if not value:
        return None
    names = [part.strip() for part in value.split(",")]
    return [name for name in names if name]


def canonical_dataset_selection(datasets: list[str] | None) -> list[str] | None:
    if not datasets:
        return None
    ordered_names = [spec["name"] for spec in DATASET_SPECS]
    valid_names = set(ordered_names)
    requested = set(datasets)
    unknown = sorted(requested.difference(valid_names))
    if unknown:
        raise ValueError(f"Unknown dataset name(s): {unknown}")
    return [name for name in ordered_names if name in requested]


def filter_datasets(df: pd.DataFrame, datasets: list[str] | None) -> pd.DataFrame:
    selected = canonical_dataset_selection(datasets)
    if selected is None:
        return df
    return df[df["dataset"].astype(str).isin(selected)].copy()


def dataset_artifact_suffix(datasets: list[str] | None) -> str:
    selected = canonical_dataset_selection(datasets)
    if selected is None:
        return ""
    return "_datasets-" + "-".join(safe_name(name) for name in selected)


def load_checkpoint_rows(
    path: Path,
    *,
    error_column: str,
    trajectory_error_column: str,
) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Missing {path}. Run `python aggregate_l2.py` first to generate l2_by_checkpoint.csv."
        )
    df = pd.read_csv(path)
    required = {
        "dataset",
        "semivalue",
        "method",
        "instance_id",
        "run_idx",
        "checkpoint_idx",
        "actual_budget",
        error_column,
        trajectory_error_column,
    }
    missing = sorted(required.difference(df.columns))
    if missing:
        raise ValueError(f"{path} is missing required columns: {missing}")
    return df


def plot_l2_trajectories(
    checkpoint_rows: pd.DataFrame,
    *,
    output_dir: Path,
    mplconfig_dir: Path,
    error_column: str,
    xscale: str,
    yscale: str,
    filetype: str,
) -> list[Path]:
    mplconfig_dir.mkdir(parents=True, exist_ok=True)
    os.environ["MPLCONFIGDIR"] = str(mplconfig_dir)
    import matplotlib.pyplot as plt

    output_dir.mkdir(parents=True, exist_ok=True)
    checkpoint_rows = filter_paper_methods(checkpoint_rows)
    summary_rows = (
        checkpoint_rows.groupby(
            ["dataset", "semivalue", "method", "checkpoint_idx", "actual_budget"],
            as_index=False,
            sort=False,
        )
        .agg(
            q10=(error_column, lambda values: values.quantile(0.10)),
            median=(error_column, "median"),
            q90=(error_column, lambda values: values.quantile(0.90)),
        )
    )
    methods = sorted(summary_rows["method"].dropna().unique(), key=method_sort_key)
    colors, _markers = _method_style(list(methods))
    by_panel: dict[tuple[str, str], list[dict[str, object]]] = defaultdict(list)
    for row in summary_rows.to_dict(orient="records"):
        by_panel[(str(row["dataset"]), str(row["semivalue"]))].append(row)

    saved: list[Path] = []
    for (dataset_name, semivalue_name), panel_rows in sorted(by_panel.items()):
        by_method: dict[str, list[dict[str, object]]] = defaultdict(list)
        for row in panel_rows:
            by_method[str(row["method"])].append(row)

        fig, ax = plt.subplots(figsize=(8.0, 5.0))
        for method_name, method_rows in sorted(
            by_method.items(),
            key=lambda item: method_sort_key(item[0]),
        ):
            method_rows = sorted(method_rows, key=lambda row: int(row["checkpoint_idx"]))
            x = np.array([row["actual_budget"] for row in method_rows], dtype=np.float64)
            y = np.array([row["median"] for row in method_rows], dtype=np.float64)
            lower = np.array([row["q10"] for row in method_rows], dtype=np.float64)
            upper = np.array([row["q90"] for row in method_rows], dtype=np.float64)
            color = colors.get(method_name)
            label = method_display_label(method_name)
            ax.plot(x, y, marker="o", linewidth=1.8, markersize=3.5, label=label, color=color)
            lower = np.maximum(lower, 0.0)
            ax.fill_between(x, lower, upper, alpha=0.16, linewidth=0, color=color)

        dataset_title = get_dataset(dataset_name)["title"]
        semivalue_title = get_semivalue(semivalue_name)["title"]
        ax.set_title(f"{dataset_title} / {semivalue_title}")
        ax.set_xlabel("Utility evaluations m")
        ax.set_ylabel(ERROR_COLUMN_LABELS.get(error_column, error_column))
        ax.set_xscale(xscale)
        if yscale == "log":
            positive = [float(row["median"]) for row in panel_rows if float(row["median"]) > 0.0]
            if positive:
                ax.set_yscale("log")
        ax.grid(True, which="both", alpha=0.25)
        ax.legend(loc="center left", bbox_to_anchor=(1.02, 0.5), frameon=False, fontsize=8)
        fig.tight_layout()
        path = output_dir / f"l2_{safe_name(dataset_name)}_{safe_name(semivalue_name)}.{filetype}"
        fig.savefig(path, dpi=220, bbox_inches="tight")
        plt.close(fig)
        saved.append(path)
    return saved


def compute_task_metrics(df: pd.DataFrame, *, error_column: str) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    key_cols = ["dataset", "semivalue", "method", "instance_id", "run_idx"]
    for key, group in df.groupby(key_cols, sort=False):
        dataset, semivalue, method, instance_id, run_idx = key
        group = group.sort_values("checkpoint_idx")
        budgets = group["actual_budget"].to_numpy(dtype=np.float64)
        errors = group[error_column].to_numpy(dtype=np.float64)
        finite = np.isfinite(budgets) & np.isfinite(errors)
        budgets = budgets[finite]
        errors = errors[finite]
        if len(errors) == 0:
            continue
        if len(errors) == 1 or budgets[-1] == budgets[0]:
            aucc = float(errors[-1])
        else:
            aucc = float(np.trapezoid(errors, budgets) / (budgets[-1] - budgets[0]))
        rows.append(
            {
                "dataset": dataset,
                "semivalue": semivalue,
                "method": method,
                "instance_id": int(instance_id),
                "run_idx": int(run_idx),
                "aucc": aucc,
                "source_error_col": error_column,
            }
        )
    return pd.DataFrame(rows)


def add_panel_best_normalization(task_metrics: pd.DataFrame) -> pd.DataFrame:
    out = task_metrics.copy()
    panel_method_mean = (
        out.groupby(["dataset", "semivalue", "method"], as_index=False)["aucc"]
        .mean()
        .rename(columns={"aucc": "method_mean"})
    )
    panel_best = (
        panel_method_mean.groupby(["dataset", "semivalue"], as_index=False)["method_mean"]
        .min()
        .rename(columns={"method_mean": "aucc_panel_best"})
    )
    out = out.merge(panel_best, on=["dataset", "semivalue"], how="left")
    denom = out["aucc_panel_best"].replace(0.0, np.nan)
    out["relative_aucc"] = out["aucc"] / denom
    return out


def summarize_for_lines(
    task_metrics: pd.DataFrame,
    *,
    normalize: str,
    band: str,
    source_error_col: str,
    raw_metrics: set[str] | None = None,
) -> pd.DataFrame:
    raw_metrics = raw_metrics or set()
    metric_cols = {
        "aucc": (
            "relative_aucc"
            if normalize == "panel_best" and "aucc" not in raw_metrics
            else "aucc"
        ),
    }
    rows = []
    for metric_name, value_col in metric_cols.items():
        grouped = task_metrics.groupby(["dataset", "semivalue", "method"], sort=False)[value_col]
        summary = grouped.agg(mean="mean", std="std", count="count").reset_index()
        summary["std"] = summary["std"].fillna(0.0)
        summary["sem"] = summary["std"] / np.sqrt(summary["count"].clip(lower=1))
        summary["metric"] = metric_name
        summary["value_col"] = value_col
        summary["source_error_col"] = source_error_col
        summary["uncertainty"] = summary[band]
        rows.append(summary)
    out = pd.concat(rows, ignore_index=True)
    out["dataset_order"] = out["dataset"].map(DATASET_ORDER).fillna(len(DATASET_ORDER)).astype(int)
    out["semivalue_order"] = out["semivalue"].map(SEMIVALUE_ORDER).fillna(len(SEMIVALUE_ORDER)).astype(int)
    methods = sorted(out["method"].dropna().unique(), key=method_sort_key)
    method_order = {method: idx for idx, method in enumerate(methods)}
    out["method_order"] = out["method"].map(method_order).fillna(len(method_order)).astype(int)
    out["method_label"] = out["method"].map(method_display_label)
    out["semivalue_label"] = out["semivalue"].map(SEMIVALUE_LABELS).fillna(out["semivalue"])
    return out.sort_values(
        ["metric", "dataset_order", "semivalue_order", "method_order", "method"]
    ).reset_index(drop=True)


def _method_style(methods: list[str]):
    import matplotlib.pyplot as plt

    cmap = plt.get_cmap("tab20", max(1, len(METHOD_SPECS)))
    colors = {}
    for method in methods:
        base_method = method_base_name(method)
        fallback_idx = METHOD_ORDER.get(base_method, len(METHOD_ORDER))
        colors[method] = REFERENCE_METHOD_COLORS.get(base_method, cmap(fallback_idx % cmap.N))
    markers_all = ["o", "s", "^", "D", "v", "P", "X", "*", "<", ">", "h", "H", "p", "8", "d", "x", "+"]
    pilot_labels = sorted(
        {
            label
            for label in (method_pilot_fraction_label(method) for method in methods)
            if label is not None
        },
        key=float,
    )
    pilot_markers = {
        label: markers_all[idx % len(markers_all)]
        for idx, label in enumerate(pilot_labels)
    }
    markers = {}
    for method in methods:
        pilot_label = method_pilot_fraction_label(method)
        base_method = method_base_name(method)
        fallback_idx = METHOD_ORDER.get(base_method, len(METHOD_ORDER))
        markers[method] = (
            pilot_markers[pilot_label]
            if pilot_label is not None
            else REFERENCE_METHOD_MARKERS.get(
                base_method,
                markers_all[fallback_idx % len(markers_all)],
            )
        )
    return colors, markers


def _make_metric_figure(plt, *, metric: str, datasets: list[str], sharey: bool):
    if metric == "aucc" and len(datasets) == 5:
        fig = plt.figure(figsize=(14.5, 9.7))
        grid = fig.add_gridspec(
            2,
            6,
            left=0.085,
            right=0.98,
            top=0.945,
            bottom=0.255,
            hspace=0.62,
            wspace=0.42,
        )
        positions = [
            grid[0, 0:2],
            grid[0, 2:4],
            grid[0, 4:6],
            grid[1, 1:3],
            grid[1, 3:5],
        ]
        axes = []
        shared_ax = None
        for position in positions:
            ax = fig.add_subplot(position, sharey=shared_ax if sharey else None)
            if shared_ax is None:
                shared_ax = ax
            axes.append(ax)
        return fig, axes

    if metric == "aucc" and len(datasets) == 1:
        fig, ax = plt.subplots(1, 1, figsize=(6.8, 4.8), sharey=sharey)
        return fig, [ax]

    fig, axes = plt.subplots(1, len(datasets), figsize=(4.8 * len(datasets), 4.6), sharey=sharey)
    if len(datasets) == 1:
        axes = [axes]
    else:
        axes = list(axes)
    return fig, axes


def plot_metric_lines(
    summary: pd.DataFrame,
    *,
    metric: str,
    output_path: Path,
    mplconfig_dir: Path,
    normalize: str,
    band: str,
    yscale: str,
    method_offset: float,
    source_error_col: str,
) -> None:
    mplconfig_dir.mkdir(parents=True, exist_ok=True)
    os.environ["MPLCONFIGDIR"] = str(mplconfig_dir)
    os.environ.setdefault("XDG_CACHE_HOME", str(mplconfig_dir))
    import matplotlib.pyplot as plt

    metric_summary = summary[summary["metric"] == metric].copy()
    is_relative = metric_summary["value_col"].astype(str).str.startswith("relative_").all()
    datasets = sorted(metric_summary["dataset"].unique(), key=lambda name: DATASET_ORDER.get(name, 10_000))
    methods = sorted(metric_summary["method"].unique(), key=method_sort_key)
    colors, markers = _method_style(methods)
    ease_method_flags = {method: method_is_easeshap(method) for method in methods}
    is_aucc_grid = metric == "aucc" and len(datasets) == 5
    is_single_aucc = metric == "aucc" and len(datasets) == 1

    semivalue_names = AUCC_SEMIVALUE_ORDER if metric == "aucc" else [spec["name"] for spec in SEMIVALUE_SPECS]
    x_base = np.arange(len(semivalue_names), dtype=float)
    semivalue_labels = [SEMIVALUE_LABELS.get(name, name) for name in semivalue_names]
    offsets = np.linspace(-method_offset, method_offset, max(len(methods), 1))
    method_offsets = {method: offsets[idx] for idx, method in enumerate(methods)}
    positive_values = metric_summary.loc[metric_summary["mean"] > 0.0, "mean"].to_numpy(dtype=float)
    min_positive = float(positive_values.min()) if len(positive_values) else 1e-16

    fig, axes = _make_metric_figure(plt, metric=metric, datasets=datasets, sharey=is_relative)

    handles = []
    for method in methods:
        label = PLOT_METHOD_LABELS.get(method, method_display_label(method))
        is_ease = ease_method_flags[method]
        linewidth = 1.6 if is_ease or not is_aucc_grid else 1.05
        markersize = 4.3 if is_ease or not is_aucc_grid else 3.3
        alpha_line = 0.95 if is_ease or not is_aucc_grid else 0.68
        handles.append(
            plt.Line2D(
                [0],
                [0],
                color=colors.get(method),
                marker=markers[method],
                linewidth=linewidth,
                markersize=markersize,
                label=label,
                alpha=alpha_line,
            )
        )

    for ax, dataset in zip(axes, datasets):
        panel = metric_summary[metric_summary["dataset"] == dataset]
        for method in methods:
            method_rows = panel[panel["method"] == method]
            if method_rows.empty:
                continue
            xs: list[float] = []
            means: list[float] = []
            errs: list[float] = []
            for semivalue_idx, semivalue in enumerate(semivalue_names):
                cur = method_rows[method_rows["semivalue"] == semivalue]
                if cur.empty:
                    continue
                row = cur.iloc[0]
                xs.append(float(x_base[semivalue_idx] + method_offsets[method]))
                means.append(float(row["mean"]))
                errs.append(float(row["uncertainty"]))
            if not xs:
                continue

            xs_arr = np.asarray(xs, dtype=float)
            means_arr = np.asarray(means, dtype=float)
            errs_arr = np.asarray(errs, dtype=float)
            if yscale == "log":
                means_arr = np.maximum(means_arr, 1e-16)
                errs_arr = np.minimum(errs_arr, means_arr - 1e-16)
            is_ease = ease_method_flags[method]
            linewidth = 1.6 if is_ease or not is_aucc_grid else 1.05
            markersize = 4.3 if is_ease or not is_aucc_grid else 3.3
            alpha_line = 0.95 if is_ease or not is_aucc_grid else 0.68
            if is_aucc_grid and len(xs_arr) > 1:
                lower = np.maximum(means_arr - errs_arr, min_positive / 5.0)
                upper = np.maximum(means_arr + errs_arr, min_positive / 5.0)
                ax.plot(
                    xs_arr,
                    means_arr,
                    color=colors.get(method),
                    marker=markers[method],
                    linewidth=linewidth,
                    markersize=markersize,
                    alpha=alpha_line,
                    zorder=3 if is_ease else 2,
                )
                ax.fill_between(
                    xs_arr,
                    lower,
                    upper,
                    color=colors.get(method),
                    alpha=0.22 if is_ease else 0.14,
                    linewidth=0,
                    zorder=1,
                )
            else:
                ax.errorbar(
                    xs_arr,
                    means_arr,
                    yerr=errs_arr,
                    color=colors.get(method),
                    marker=markers[method],
                    linewidth=linewidth,
                    markersize=markersize,
                    alpha=alpha_line,
                    capsize=2.0,
                    capthick=0.8 if is_aucc_grid else 0.9,
                    zorder=3 if is_ease else 2,
                )

        if is_aucc_grid:
            title_fontsize = 16.0
        elif is_single_aucc:
            title_fontsize = 13.0
        else:
            title_fontsize = 10.5
        ax.set_title(DATASET_TITLES.get(dataset, dataset), fontsize=title_fontsize, pad=7)
        ax.set_xticks(x_base)
        ax.set_xticklabels(
            semivalue_labels,
            rotation=28 if is_aucc_grid else 30,
            ha="right",
            fontsize=15.0 if is_aucc_grid else (10.5 if is_single_aucc else 8.5),
        )
        x_margin = 0.45 if is_aucc_grid else 0.55
        ax.set_xlim(float(x_base[0] - x_margin), float(x_base[-1] + x_margin))
        if yscale == "log":
            ax.set_yscale("log")
            if is_relative:
                ax.set_ylim(bottom=0.8)
        if is_aucc_grid:
            ax.tick_params(axis="y", which="major", labelsize=15.0)
            ax.tick_params(axis="y", which="minor", labelsize=11.0)
        ax.grid(True, axis="y", which="major", color="#d9d9d9", linewidth=0.65)
        ax.grid(True, axis="y", which="minor", color="#eeeeee", linewidth=0.45)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        if is_relative:
            ax.axhline(1.0, color="black", linewidth=0.75, linestyle="--", alpha=0.35)

    source_label = ERROR_COLUMN_LABELS.get(source_error_col, source_error_col)
    if metric == "aucc":
        metric_label = "AUCC"
        raw_label = f"AUCC ({source_label})"
        relative_label = f"Relative AUCC ({source_label}; panel best = 1)"
    else:
        metric_label = f"Final {source_label}"
        raw_label = f"Final {source_label}"
        relative_label = f"Relative final {source_label} (panel best = 1)"
    ylabel = relative_label if is_relative else raw_label
    if is_aucc_grid:
        fig.text(
            0.035,
            0.595,
            "AUCC",
            rotation="vertical",
            va="center",
            ha="center",
            fontsize=18.0 if source_error_col == "rel_l2_error" else 18.4,
        )
    else:
        axes[0].set_ylabel(f"{ylabel}; lower is better", fontsize=10.5)
    note_y = None if (is_aucc_grid or is_single_aucc) else -0.03
    legend_y = 0.035 if is_aucc_grid else (-0.22 if is_single_aucc else -0.25)
    tight_rect = (0.0, 0.02, 1.0, 0.98)

    if not is_aucc_grid and not is_single_aucc:
        fig.suptitle(f"{metric_label} by Dataset and Semivalue", fontsize=14, fontweight="bold", y=1.02)
    if note_y is not None:
        fig.text(0.5, note_y, f"Error bars show +/- 1 {band} over explained instances.", ha="center", fontsize=9)
    if is_aucc_grid:
        legend_cols = min(5, len(handles))
    elif is_single_aucc:
        legend_cols = min(4, len(handles))
    else:
        legend_cols = min(7, len(handles))
    legend_kwargs = {
        "handles": handles,
        "loc": "lower center",
        "ncol": legend_cols,
        "bbox_to_anchor": (0.5, legend_y),
        "fontsize": 11.4 if is_aucc_grid else (8.0 if is_single_aucc else 7.2),
        "frameon": not is_aucc_grid,
    }
    if is_aucc_grid:
        legend_kwargs.update({"handlelength": 1.9, "columnspacing": 1.0, "labelspacing": 0.45})
    fig.legend(**legend_kwargs)
    if not is_aucc_grid:
        fig.tight_layout(rect=tight_rect)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=260, bbox_inches="tight")
    plt.close(fig)


